"""Mint workflow package.

The historical single-module API is preserved: every public and private name that
used to live in ``mint_cli.workflow`` is importable from here. The implementation is
split by concern:

- ``context``: Module context: loading a module's spec, config, metadata, and the payloads handed to renderers.
- ``planning``: Render planning: which unit range a render touches and why (metadata drift, explicit ranges).
- ``scaffold``: Project scaffolding: `mint init` and `mint new` templates and writers.
- ``lint``: Spec linting: vague wording, missing testable assertions, threshold boundary checks.
- ``health``: Project and module health: `mint doctor`, `mint healthcheck`, `mint next`, `mint status`.
- ``reports``: Run reports and attempt manifests: `mint report` and `mint inspect`.
- ``maintenance``: Housekeeping commands: `mint clean`, `mint drift`, `mint prune`.
- ``stylelock``: Style-lock enforcement: detecting and explaining style-lock violations in rendered files.
- ``interface``: Interface tracking: public stubs, literal warnings, and interface-change detection for dependents.
- ``app``: Running rendered modules as an app: `mint env`, `mint run`, `mint exec`.
- ``engine``: The render loop: unit and conformance phases, gates, retries, budgets, and commits.
"""

